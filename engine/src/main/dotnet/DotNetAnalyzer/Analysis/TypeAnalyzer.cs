using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using DotNetAnalyzer.Model;

namespace DotNetAnalyzer.Analysis;

public class TypeAnalyzer
{
    public List<Component> AnalyzeTypes(Compilation compilation)
    {
        // Primary path: enumerate types via Compilation.GlobalNamespace.
        // Language-agnostic — works for both C# and VB compilations because
        // INamedTypeSymbol is shared and class/interface kinds are first-class.
        var components = new List<Component>();
        var declaredTypes = EnumerateDeclaredTypes(compilation).ToList();

        foreach (var typeSymbol in declaredTypes)
        {
            // Filter to user-declared classes, interfaces and structs / VB modules.
            // Enums are intentionally excluded (preserve existing behavior).
            if (typeSymbol.TypeKind != TypeKind.Class
                && typeSymbol.TypeKind != TypeKind.Interface
                && typeSymbol.TypeKind != TypeKind.Struct
                && typeSymbol.TypeKind != TypeKind.Module)
            {
                continue;
            }

            // Skip compiler-generated types that have no source declarations.
            // VB injects synthetic types like `My.MyApplication`, `My.MySettings`,
            // `My.Resources` etc. They have an empty DeclaringSyntaxReferences and
            // must not appear as components.
            if (typeSymbol.DeclaringSyntaxReferences.IsDefaultOrEmpty)
                continue;

            // Skip explicit autogenerated source files.
            bool allDeclaredInAutogen = typeSymbol.DeclaringSyntaxReferences
                .All(r => Common.AutogeneratedFileFilter.IsAutogenerated(r.SyntaxTree?.FilePath ?? ""));
            if (allDeclaredInAutogen)
                continue;

            var fqName = GetFullyQualifiedName(typeSymbol);

            var component = new Component
            {
                Id = fqName,
                Files = GetDeclarationFilePaths(typeSymbol),
                Loc = CountNonBlankNonCommentLinesFromSymbol(typeSymbol),
                IsInterface = typeSymbol.TypeKind == TypeKind.Interface,
                Annotations = ExtractAnnotationsFromSymbol(typeSymbol),
            };

            // Base class
            if (typeSymbol.BaseType != null
                && typeSymbol.BaseType.SpecialType != SpecialType.System_Object
                && typeSymbol.BaseType.Name != "Object"
                && typeSymbol.BaseType.Name != "ValueType")
            {
                component.Extends = GetFullyQualifiedName(typeSymbol.BaseType);
            }

            component.Implements = typeSymbol.Interfaces
                .Select(i => GetFullyQualifiedName(i))
                .ToList();

            components.Add(component);
        }

        // Fallback path (no symbols available, e.g. a degenerate compilation):
        // walk C# syntax. VB syntactic fallback is intentionally omitted because
        // we always carry semantic models for VB through VbProjectLoader, which
        // even in Adhoc mode produces a populated GlobalNamespace.
        if (components.Count == 0)
        {
            components.AddRange(AnalyzeViaCSharpSyntax(compilation));
        }

        return components;
    }

    private static IEnumerable<INamedTypeSymbol> EnumerateDeclaredTypes(Compilation compilation)
    {
        var assemblySymbol = compilation.Assembly;
        return Walk(assemblySymbol.GlobalNamespace);

        static IEnumerable<INamedTypeSymbol> Walk(INamespaceSymbol ns)
        {
            foreach (var type in ns.GetTypeMembers())
            {
                yield return type;

                foreach (var nested in WalkNested(type))
                    yield return nested;
            }

            foreach (var sub in ns.GetNamespaceMembers())
                foreach (var t in Walk(sub))
                    yield return t;
        }

        static IEnumerable<INamedTypeSymbol> WalkNested(INamedTypeSymbol type)
        {
            foreach (var nested in type.GetTypeMembers())
            {
                yield return nested;
                foreach (var deeper in WalkNested(nested))
                    yield return deeper;
            }
        }
    }

    private static List<string> GetDeclarationFilePaths(INamedTypeSymbol symbol)
    {
        var files = symbol.DeclaringSyntaxReferences
            .Select(r => GetRelativeFilePath(r.SyntaxTree?.FilePath ?? "unknown"))
            .Distinct(StringComparer.Ordinal)
            .ToList();

        if (files.Count == 0)
            files.Add("unknown");

        return files;
    }

    private static int CountNonBlankNonCommentLinesFromSymbol(INamedTypeSymbol symbol)
    {
        int total = 0;
        foreach (var reference in symbol.DeclaringSyntaxReferences)
        {
            var node = reference.GetSyntax();

            // VB INamedTypeSymbol references point at the head statement
            // (ClassStatementSyntax / ModuleStatementSyntax / etc.) which is
            // a single line. Walk up to the enclosing BlockSyntax so we count
            // the full type body. C# references already point at the full
            // ClassDeclarationSyntax, so this no-ops for C#.
            if (node.SyntaxTree.Options.Language == LanguageNames.VisualBasic
                && node.Parent != null
                && node.Parent.GetType().Name.EndsWith("BlockSyntax", StringComparison.Ordinal))
            {
                node = node.Parent;
            }

            total += CountNonBlankNonCommentLines(node);
        }
        return total;
    }

    private static List<string> ExtractAnnotationsFromSymbol(INamedTypeSymbol symbol)
    {
        var annotations = new List<string>();

        foreach (var attr in symbol.GetAttributes())
        {
            var attrClassName = attr.AttributeClass?.Name;
            if (string.IsNullOrEmpty(attrClassName))
                continue;

            // Strip "Attribute" suffix to align with existing convention.
            if (attrClassName.EndsWith("Attribute", StringComparison.Ordinal))
                attrClassName = attrClassName.Substring(0, attrClassName.Length - "Attribute".Length);

            annotations.Add(attrClassName);
        }

        return annotations;
    }

    // ─── Legacy C# syntactic fallback (preserved for compatibility) ──────────

    private static IEnumerable<Component> AnalyzeViaCSharpSyntax(Compilation compilation)
    {
        foreach (var syntaxTree in compilation.SyntaxTrees)
        {
            SemanticModel? semanticModel = null;
            try
            {
                semanticModel = compilation.GetSemanticModel(syntaxTree);
            }
            catch
            {
                // continue without semantic model
            }

            var root = syntaxTree.GetRoot();
            var typeDeclarations = root.DescendantNodes()
                .OfType<TypeDeclarationSyntax>()
                .Where(t => t is ClassDeclarationSyntax or InterfaceDeclarationSyntax);

            foreach (var typeDecl in typeDeclarations)
            {
                INamedTypeSymbol? typeSymbol = null;
                if (semanticModel != null)
                {
                    typeSymbol = semanticModel.GetDeclaredSymbol(typeDecl) as INamedTypeSymbol;
                }

                var fullyQualifiedName = typeSymbol != null
                    ? GetFullyQualifiedName(typeSymbol)
                    : GetFallbackName(typeDecl);

                var component = new Component
                {
                    Id = fullyQualifiedName,
                    Files = new List<string> { GetRelativeFilePath(syntaxTree.FilePath) },
                    Loc = CountNonBlankNonCommentLines(typeDecl),
                    IsInterface = typeSymbol != null
                        ? typeSymbol.TypeKind == TypeKind.Interface
                        : typeDecl is InterfaceDeclarationSyntax,
                    Annotations = ExtractAnnotationsFromSyntax(typeDecl, semanticModel),
                };

                if (typeSymbol != null)
                {
                    if (typeSymbol.BaseType != null
                        && typeSymbol.BaseType.SpecialType != SpecialType.System_Object
                        && typeSymbol.BaseType.Name != "Object")
                    {
                        component.Extends = GetFullyQualifiedName(typeSymbol.BaseType);
                    }

                    component.Implements = typeSymbol.Interfaces
                        .Select(i => GetFullyQualifiedName(i))
                        .ToList();
                }
                else if (typeDecl is ClassDeclarationSyntax classDecl && classDecl.BaseList != null)
                {
                    foreach (var baseType in classDecl.BaseList.Types)
                    {
                        component.Implements.Add(baseType.Type.ToString());
                    }
                }

                yield return component;
            }
        }
    }

    /// <summary>Namespaces + simple name; shared with the 020 C# procedure adapter.</summary>
    internal static string GetFullyQualifiedName(INamedTypeSymbol symbol)
    {
        var parts = new List<string>();
        var current = symbol.ContainingNamespace;
        while (current != null && !current.IsGlobalNamespace)
        {
            parts.Insert(0, current.Name);
            current = current.ContainingNamespace;
        }
        parts.Add(symbol.Name);
        return string.Join(".", parts);
    }

    private static string GetFallbackName(TypeDeclarationSyntax typeDecl)
    {
        var parts = new List<string>();
        var parent = typeDecl.Parent;
        while (parent != null)
        {
            if (parent is BaseNamespaceDeclarationSyntax nsDecl)
                parts.Insert(0, nsDecl.Name.ToString());
            parent = parent.Parent;
        }
        parts.Add(typeDecl.Identifier.Text);
        return string.Join(".", parts);
    }

    private static string GetRelativeFilePath(string filePath)
    {
        if (string.IsNullOrEmpty(filePath))
            return "unknown";
        return filePath.Replace('\\', '/');
    }

    private static int CountNonBlankNonCommentLines(SyntaxNode node)
    {
        var text = node.GetText();
        var count = 0;
        var inBlockComment = false;

        foreach (var textLine in text.Lines)
        {
            var line = textLine.ToString().Trim();

            if (inBlockComment)
            {
                if (line.Contains("*/"))
                    inBlockComment = false;
                continue;
            }

            if (string.IsNullOrWhiteSpace(line))
                continue;

            // C#-style line comments
            if (line.StartsWith("//"))
                continue;

            // VB line comments
            if (line.StartsWith("'") || line.StartsWith("REM ", StringComparison.OrdinalIgnoreCase) || line.Equals("REM", StringComparison.OrdinalIgnoreCase))
                continue;

            if (line.StartsWith("/*"))
            {
                inBlockComment = !line.Contains("*/");
                continue;
            }

            count++;
        }

        return count;
    }

    private static List<string> ExtractAnnotationsFromSyntax(TypeDeclarationSyntax typeDecl, SemanticModel? semanticModel)
    {
        var annotations = new List<string>();

        foreach (var attributeList in typeDecl.AttributeLists)
        {
            foreach (var attribute in attributeList.Attributes)
            {
                string name;

                if (semanticModel != null)
                {
                    var symbolInfo = semanticModel.GetSymbolInfo(attribute);
                    var attrSymbol = symbolInfo.Symbol?.ContainingType;
                    name = attrSymbol != null ? attrSymbol.Name : attribute.Name.ToString();
                }
                else
                {
                    name = attribute.Name.ToString();
                }

                if (name.EndsWith("Attribute"))
                    name = name.Substring(0, name.Length - "Attribute".Length);

                annotations.Add(name);
            }
        }

        return annotations;
    }
}
