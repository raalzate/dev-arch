namespace DotNetAnalyzer.Analysis.Common;

public static class AutogeneratedFileFilter
{
    private static readonly string[] ExactFilenames =
    {
        "Reference.vb",
        "Resources.Designer.vb",
        "Settings.Designer.vb",
        "Application.Designer.vb",
    };

    public static bool IsAutogenerated(string filePath)
    {
        if (string.IsNullOrEmpty(filePath))
            return false;

        // Cross-platform filename extraction: split on both '/' and '\'
        // (Path.GetFileName on macOS/Linux does not recognise '\' as separator).
        var lastSeparator = filePath.LastIndexOfAny(new[] { '/', '\\' });
        var name = lastSeparator >= 0 ? filePath[(lastSeparator + 1)..] : filePath;

        if (string.IsNullOrEmpty(name))
            return false;

        foreach (var exact in ExactFilenames)
        {
            if (string.Equals(name, exact, StringComparison.OrdinalIgnoreCase))
                return true;
        }

        // Match X.Designer.vb (case-insensitive) but NOT a file literally named "Designer.vb"
        if (name.EndsWith(".Designer.vb", StringComparison.OrdinalIgnoreCase) &&
            name.Length > ".Designer.vb".Length)
        {
            return true;
        }

        return false;
    }
}
