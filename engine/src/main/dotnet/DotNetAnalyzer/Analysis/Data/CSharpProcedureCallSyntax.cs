using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace DotNetAnalyzer.Analysis.Data;

/// <summary>
/// C# adapter of <see cref="IProcedureCallSyntax"/>: one instance per type declaration, identified like
/// <c>TypeAnalyzer</c> (namespaces + simple name). Nodes of nested types belong to the nested type.
/// </summary>
public sealed class CSharpProcedureCallSyntax : IProcedureCallSyntax
{
    private readonly TypeDeclarationSyntax _declaration;

    private CSharpProcedureCallSyntax(string id, TypeDeclarationSyntax declaration)
    {
        ComponentId = id;
        _declaration = declaration;
    }

    public static IEnumerable<IProcedureCallSyntax> ForCompilation(Compilation compilation)
    {
        foreach (var tree in compilation.SyntaxTrees.OrderBy(t => t.FilePath, StringComparer.Ordinal))
        {
            if (Common.AutogeneratedFileFilter.IsAutogenerated(tree.FilePath ?? ""))
                continue;
            SemanticModel? model = null;
            try
            {
                model = compilation.GetSemanticModel(tree);
            }
            catch
            {
                // syntax-only fallback below
            }

            foreach (var declaration in tree.GetRoot().DescendantNodes().OfType<TypeDeclarationSyntax>())
            {
                var symbol = model?.GetDeclaredSymbol(declaration) as INamedTypeSymbol;
                var id = symbol != null ? TypeAnalyzer.GetFullyQualifiedName(symbol) : FallbackName(declaration);
                yield return new CSharpProcedureCallSyntax(id, declaration);
            }
        }
    }

    public string ComponentId { get; }

    public string FileName => Path.GetFileName(_declaration.SyntaxTree.FilePath ?? "") is { Length: > 0 } f ? f : "unknown";

    public IEnumerable<CallCandidate> Invocations()
    {
        foreach (var invocation in OwnNodes().OfType<InvocationExpressionSyntax>())
        {
            var name = invocation.Expression switch
            {
                MemberAccessExpressionSyntax access => access.Name.Identifier.ValueText,
                IdentifierNameSyntax identifier => identifier.Identifier.ValueText,
                GenericNameSyntax generic => generic.Identifier.ValueText,
                _ => null,
            };
            if (name == null)
                continue;

            var positional = new List<string?>();
            var named = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (var argument in invocation.ArgumentList.Arguments)
            {
                if (argument.NameColon != null)
                    named[argument.NameColon.Name.Identifier.ValueText] = MemberText(argument.Expression);
                else
                    positional.Add(Literal(argument.Expression));
            }

            yield return new CallCandidate(name, positional, named, Line(invocation));
        }
    }

    public bool UsesStoredProcedureCommandType() =>
        OwnNodes().OfType<MemberAccessExpressionSyntax>().Any(m => m.Name.Identifier.ValueText == "StoredProcedure");

    public IEnumerable<TextCandidate> CommandTexts()
    {
        foreach (var node in OwnNodes())
        {
            switch (node)
            {
                case AssignmentExpressionSyntax assignment when assignment.IsKind(SyntaxKind.SimpleAssignmentExpression)
                    && NameOf(assignment.Left) == "CommandText":
                    yield return new TextCandidate(Literal(assignment.Right), Line(assignment));
                    break;
                case ObjectCreationExpressionSyntax creation
                    when creation.Type.ToString().EndsWith("Command", StringComparison.Ordinal)
                         && creation.ArgumentList?.Arguments.FirstOrDefault() is { NameColon: null } first:
                    yield return new TextCandidate(Literal(first.Expression), Line(creation));
                    break;
            }
        }
    }

    private IEnumerable<SyntaxNode> OwnNodes() =>
        _declaration.DescendantNodes(n => ReferenceEquals(n, _declaration) || n is not TypeDeclarationSyntax)
            .Where(n => n is not TypeDeclarationSyntax);

    private static string? NameOf(ExpressionSyntax left) => left switch
    {
        MemberAccessExpressionSyntax access => access.Name.Identifier.ValueText,
        IdentifierNameSyntax identifier => identifier.Identifier.ValueText,
        _ => null,
    };

    private static string? Literal(ExpressionSyntax expression) => CsStringFolder.FoldLiteral(expression);

    private static string MemberText(ExpressionSyntax expression) => expression switch
    {
        MemberAccessExpressionSyntax access => access.Name.Identifier.ValueText,
        _ => expression.ToString(),
    };

    private static string FallbackName(TypeDeclarationSyntax declaration)
    {
        var parts = new List<string>();
        for (var parent = declaration.Parent; parent != null; parent = parent.Parent)
        {
            if (parent is BaseNamespaceDeclarationSyntax ns)
                parts.Insert(0, ns.Name.ToString());
        }

        parts.Add(declaration.Identifier.ValueText);
        return string.Join(".", parts);
    }

    private static int Line(SyntaxNode node) => node.GetLocation().GetLineSpan().StartLinePosition.Line + 1;
}
