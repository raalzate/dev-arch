using DotNetAnalyzer.Analysis.Common;
using FluentAssertions;
using Xunit;

namespace DotNetAnalyzer.Tests.Analysis.Common;

public class AutogeneratedFileFilterTests
{
    [Theory(DisplayName = "TS-005: Designer.vb suffix is autogenerated")]
    [InlineData("MainForm.Designer.vb")]
    [InlineData("/proj/Forms/MainForm.Designer.vb")]
    [InlineData(@"C:\proj\Forms\OrderForm.Designer.vb")]
    [InlineData("AccountTypeForm.Designer.vb")]
    public void DesignerVb_IsAutogenerated(string path)
    {
        AutogeneratedFileFilter.IsAutogenerated(path).Should().BeTrue();
    }

    [Theory(DisplayName = "TS-005: lowercase designer.vb variant is autogenerated")]
    [InlineData("mainform.designer.vb")]
    [InlineData("/proj/Forms/mainform.designer.vb")]
    public void LowercaseDesignerVb_IsAutogenerated(string path)
    {
        AutogeneratedFileFilter.IsAutogenerated(path).Should().BeTrue();
    }

    [Theory(DisplayName = "TS-005: Reference.vb is autogenerated")]
    [InlineData("Reference.vb")]
    [InlineData("/proj/Service References/PaymentService/Reference.vb")]
    [InlineData(@"C:\proj\Web References\HolidayService\Reference.vb")]
    public void ReferenceVb_IsAutogenerated(string path)
    {
        AutogeneratedFileFilter.IsAutogenerated(path).Should().BeTrue();
    }

    [Theory(DisplayName = "TS-005: My Project Designer files are autogenerated")]
    [InlineData("Resources.Designer.vb")]
    [InlineData("Settings.Designer.vb")]
    [InlineData("Application.Designer.vb")]
    [InlineData("/proj/My Project/Resources.Designer.vb")]
    [InlineData("/proj/My Project/Settings.Designer.vb")]
    [InlineData("/proj/My Project/Application.Designer.vb")]
    public void MyProjectDesigners_AreAutogenerated(string path)
    {
        AutogeneratedFileFilter.IsAutogenerated(path).Should().BeTrue();
    }

    [Theory(DisplayName = "TS-005: regular VB files are NOT autogenerated")]
    [InlineData("Class1.vb")]
    [InlineData("OrderController.vb")]
    [InlineData("EntityAdapter.vb")]
    [InlineData("MainForm.vb")]
    [InlineData("/proj/Common/Reference.cs")]   // .cs file with similar name — out of scope here
    [InlineData("/proj/Designer.vb")]            // file literally named "Designer.vb" without prefix
    [InlineData("ReferenceData.vb")]             // not exactly "Reference.vb"
    public void NonAutogenerated_ReturnsFalse(string path)
    {
        AutogeneratedFileFilter.IsAutogenerated(path).Should().BeFalse();
    }

    [Theory(DisplayName = "TS-005: empty / null-like paths are not autogenerated")]
    [InlineData("")]
    public void EmptyPath_ReturnsFalse(string path)
    {
        AutogeneratedFileFilter.IsAutogenerated(path).Should().BeFalse();
    }
}
