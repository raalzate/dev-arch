using DotNetAnalyzer.Analysis;
using FluentAssertions;
using Xunit;

namespace DotNetAnalyzer.Tests.Analysis.Vb;

[Trait("Category", "VbLegacy")]
public class VbProjectAnalyzerIntegrationTests
{
    private static string MinimalFixturePath
        => Path.Combine(AppContext.BaseDirectory, "Fixtures", "VbLegacy", "MinimalVbProject", "Minimal.vbproj");

    [Fact(DisplayName = "TS-001: ProjectAnalyzer dispatches .vbproj path through VB pipeline and produces a non-empty graph")]
    public async Task Analyze_VbProject_ProducesNonEmptyGraph()
    {
        var analyzer = new ProjectAnalyzer();

        var graph = await analyzer.AnalyzeProjectAsync(MinimalFixturePath);

        graph.Should().NotBeNull();
        graph.Components.Should().NotBeEmpty();
        graph.Components.Should().Contain(c => c.Id == "MinimalVb.Greeter");
    }

    [Fact(DisplayName = "TS-005: ProjectAnalyzer excludes Designer.vb from components")]
    public async Task Analyze_VbProject_ExcludesAutogenerated()
    {
        var analyzer = new ProjectAnalyzer();

        var graph = await analyzer.AnalyzeProjectAsync(MinimalFixturePath);

        graph.Components
            .SelectMany(c => c.Files)
            .Should().NotContain(f => f.EndsWith("MainForm.Designer.vb", StringComparison.OrdinalIgnoreCase));
    }

    [Fact(DisplayName = "TS-002: Directory containing a .vbproj is auto-discovered")]
    public async Task Analyze_DirectoryWithVbProj_LoadsIt()
    {
        var dir = Path.GetDirectoryName(MinimalFixturePath)!;
        var analyzer = new ProjectAnalyzer();

        var graph = await analyzer.AnalyzeProjectAsync(dir);

        graph.Components.Should().Contain(c => c.Id == "MinimalVb.Greeter");
    }

    [Fact(DisplayName = "TS-006: Output meta.source reflects the loader path")]
    public async Task Analyze_VbProject_MetaSourceIsKnown()
    {
        var analyzer = new ProjectAnalyzer();

        var graph = await analyzer.AnalyzeProjectAsync(MinimalFixturePath);

        graph.Meta!.Source.Should().BeOneOf("roslyn", "roslyn-fallback");
    }

    [Fact(DisplayName = "TS-014: Output is deterministic — components ordered by id")]
    public async Task Analyze_VbProject_ComponentsOrderedDeterministically()
    {
        var analyzer = new ProjectAnalyzer();

        var graph = await analyzer.AnalyzeProjectAsync(MinimalFixturePath);

        var ids = graph.Components.Select(c => c.Id).ToList();
        ids.Should().BeInAscendingOrder(StringComparer.Ordinal);
    }

    [Fact(DisplayName = "TS-014: Two consecutive runs produce the same components/edges (excl. meta.collected_at)")]
    public async Task Analyze_VbProject_TwoRunsIdentical()
    {
        var analyzer1 = new ProjectAnalyzer();
        var graph1 = await analyzer1.AnalyzeProjectAsync(MinimalFixturePath);

        var analyzer2 = new ProjectAnalyzer();
        var graph2 = await analyzer2.AnalyzeProjectAsync(MinimalFixturePath);

        graph1.Components.Select(c => c.Id).Should().Equal(graph2.Components.Select(c => c.Id));
        graph1.Edges.Select(e => $"{e.From}->{e.To}:{e.Type}")
              .Should().Equal(graph2.Edges.Select(e => $"{e.From}->{e.To}:{e.Type}"));
    }
}
