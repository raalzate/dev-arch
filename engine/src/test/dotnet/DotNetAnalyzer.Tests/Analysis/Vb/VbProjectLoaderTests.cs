using DotNetAnalyzer.Analysis.Vb;
using FluentAssertions;
using Microsoft.CodeAnalysis;
using Xunit;

namespace DotNetAnalyzer.Tests.Analysis.Vb;

public class VbProjectLoaderTests
{
    private static string MinimalFixturePath
        => Path.Combine(AppContext.BaseDirectory, "Fixtures", "VbLegacy", "MinimalVbProject", "Minimal.vbproj");

    private static string MinimalFixtureDir
        => Path.GetDirectoryName(MinimalFixturePath)!;

    [Fact(DisplayName = "TS-001: Adhoc loader produces a non-null Compilation for a minimal .vbproj")]
    public void Adhoc_LoadsMinimalProject()
    {
        File.Exists(MinimalFixturePath).Should().BeTrue("fixture must be copied to output");

        var compilation = VbProjectLoader.LoadAdhoc(MinimalFixturePath);

        compilation.Should().NotBeNull();
        compilation!.Language.Should().Be(LanguageNames.VisualBasic);
    }

    [Fact(DisplayName = "TS-001: Adhoc loader resolves a directory path the same as a .vbproj path")]
    public void Adhoc_AcceptsDirectoryPath()
    {
        var compilation = VbProjectLoader.LoadAdhoc(MinimalFixtureDir);

        compilation.Should().NotBeNull();
        compilation!.Language.Should().Be(LanguageNames.VisualBasic);
    }

    [Fact(DisplayName = "TS-005: Autogenerated .vb files are excluded from the compilation")]
    public void Adhoc_ExcludesAutogeneratedFiles()
    {
        var compilation = VbProjectLoader.LoadAdhoc(MinimalFixturePath);

        compilation.Should().NotBeNull();

        var includedPaths = compilation!.SyntaxTrees.Select(t => t.FilePath).ToList();
        includedPaths.Should().Contain(p => p.EndsWith("Class1.vb", StringComparison.OrdinalIgnoreCase));
        includedPaths.Should().NotContain(p => p.EndsWith("MainForm.Designer.vb", StringComparison.OrdinalIgnoreCase));
    }

    [Fact(DisplayName = "TS-001: Compilation parses a real VB type — Greeter.Hello")]
    public void Adhoc_CompilationContainsExpectedType()
    {
        var compilation = VbProjectLoader.LoadAdhoc(MinimalFixturePath);

        compilation.Should().NotBeNull();

        var greeter = compilation!.GetTypeByMetadataName("MinimalVb.Greeter");
        greeter.Should().NotBeNull("the loader must produce a compilation that resolves declared types via metadata name");
    }

    [Fact(DisplayName = "TS-013: Empty directory returns null without throwing")]
    public void Adhoc_EmptyDirectoryReturnsNull()
    {
        var temp = Path.Combine(Path.GetTempPath(), "vbloader-empty-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(temp);
        try
        {
            var compilation = VbProjectLoader.LoadAdhoc(temp);
            compilation.Should().BeNull();
        }
        finally
        {
            Directory.Delete(temp, recursive: true);
        }
    }

    [Fact(DisplayName = "TS-013: Non-existent path returns null without throwing")]
    public void Adhoc_NonExistentPathReturnsNull()
    {
        var bogus = Path.Combine(Path.GetTempPath(), "definitely-does-not-exist-" + Guid.NewGuid().ToString("N"));

        var compilation = VbProjectLoader.LoadAdhoc(bogus);

        compilation.Should().BeNull();
    }

    [Fact(DisplayName = "TS-013: Per-file parse failure does not abort load (parser is permissive but graceful)")]
    public void Adhoc_HandlesParseFailureGracefully()
    {
        // Roslyn's VB parser is forgiving; even garbage produces a tree (with diagnostics).
        // The contract here is "no exception escapes the loader and at least one valid file produces a tree".
        var temp = Path.Combine(Path.GetTempPath(), "vbloader-mixed-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(temp);
        try
        {
            File.WriteAllText(Path.Combine(temp, "Good.vb"),
                "Namespace N\n  Public Class C\n  End Class\nEnd Namespace\n");
            File.WriteAllText(Path.Combine(temp, "Garbage.vb"),
                "{{{ this is not VB at all (((");

            var compilation = VbProjectLoader.LoadAdhoc(temp);

            compilation.Should().NotBeNull();
            compilation!.SyntaxTrees.Should().HaveCountGreaterThanOrEqualTo(1);
            compilation.GetTypeByMetadataName("N.C").Should().NotBeNull();
        }
        finally
        {
            Directory.Delete(temp, recursive: true);
        }
    }

    [Fact(DisplayName = "TS-001: SyntaxTrees are sorted by FilePath ordinal for determinism")]
    public void Adhoc_SyntaxTreesAreOrdered()
    {
        var compilation = VbProjectLoader.LoadAdhoc(MinimalFixturePath);
        compilation.Should().NotBeNull();

        var paths = compilation!.SyntaxTrees.Select(t => t.FilePath).ToArray();
        var sorted = paths.OrderBy(p => p, StringComparer.Ordinal).ToArray();

        paths.Should().Equal(sorted,
            "syntax trees must be in deterministic ordinal order to satisfy SC-008 byte-identical output");
    }

    [Fact(DisplayName = "TS-015: WarnIfNonWindows is a no-op on Windows and emits warning elsewhere")]
    public void WarnIfNonWindows_DoesNotThrow()
    {
        // Both Windows and non-Windows runs must not throw; the side effect is stderr text.
        // Behavior assertion is environment-dependent; we only assert no exception.
        VbProjectLoader.WarnIfNonWindows();
    }

    [Fact(DisplayName = "TS-015: IsWindows reflects the current runtime platform")]
    public void IsWindows_ReflectsRuntime()
    {
        VbProjectLoader.IsWindows.Should().Be(
            System.Runtime.InteropServices.RuntimeInformation.IsOSPlatform(
                System.Runtime.InteropServices.OSPlatform.Windows));
    }

    [Fact(DisplayName = "TS-005: StripAutogenerated removes Designer.vb trees from a compilation")]
    public void StripAutogenerated_RemovesDesignerTrees()
    {
        var compilation = VbProjectLoader.LoadAdhoc(MinimalFixturePath);
        compilation.Should().NotBeNull();

        // Re-add a designer tree to verify Strip works regardless of original glob filtering.
        var designerSource = "Namespace MinimalVb : Partial Class Foo : End Class : End Namespace";
        var designerTree = Microsoft.CodeAnalysis.VisualBasic.VisualBasicSyntaxTree.ParseText(
            designerSource, path: Path.Combine(MinimalFixtureDir, "Foo.Designer.vb"));

        var withDesigner = compilation!.AddSyntaxTrees(designerTree);
        var stripped = VbProjectLoader.StripAutogenerated(withDesigner);

        stripped.SyntaxTrees.Should().NotContain(designerTree);
        stripped.SyntaxTrees.Should().HaveCount(withDesigner.SyntaxTrees.Count() - 1);
    }
}
