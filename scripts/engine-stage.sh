#!/usr/bin/env bash
# Stages the locally built engine where the web looks for it by default (FR-009, FR-013):
#   web/engine-dist/engine.jar                 <- engine/target/java-dependency-extractor.jar
#   web/engine-dist/dotnet-analyzer-publish/   <- engine/target/dotnet-analyzer-publish/
#   web/engine-dist/dotnet-analyzer            launcher next to the jar (the engine looks it up there first)
set -u
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

jar="$ENGINE_DIR/target/$ENGINE_JAR_NAME"
publish="$ENGINE_DIR/target/dotnet-analyzer-publish"
if [ ! -f "$jar" ]; then
  status build stage FAIL "engine/target/$ENGINE_JAR_NAME not found; run make build"
  exit 1
fi
rm -rf "$ENGINE_DIST"
mkdir -p "$ENGINE_DIST"
cp "$jar" "$ENGINE_DIST/engine.jar"
if [ -x "$publish/dotnet-analyzer" ]; then
  export_dotnet_root
  cp -R "$publish" "$ENGINE_DIST/dotnet-analyzer-publish"
  {
    echo '#!/usr/bin/env bash'
    echo '# Generated by scripts/engine-stage.sh: launches the framework-dependent dotnet-analyzer.'
    [ -n "${DOTNET_ROOT:-}" ] && echo "export DOTNET_ROOT=\"\${DOTNET_ROOT:-$DOTNET_ROOT}\""
    echo 'exec "$(cd "$(dirname "$0")" && pwd)/dotnet-analyzer-publish/dotnet-analyzer" "$@"'
  } > "$ENGINE_DIST/dotnet-analyzer"
  chmod +x "$ENGINE_DIST/dotnet-analyzer"
  status build stage OK "web/engine-dist/engine.jar, web/engine-dist/dotnet-analyzer"
else
  status build stage OK "web/engine-dist/engine.jar (no .NET analyzer published)"
fi
