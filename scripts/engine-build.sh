#!/usr/bin/env bash
# Builds the engine (FR-009): the Java fat JAR with Maven (JAVA_HOME honored, tests skipped) and the .NET
# analyzer published framework-dependent (a single-file bundle cannot load MSBuild, BUG-005), installed as
# engine/target/dotnet-analyzer next to the jar, where the engine looks it up first.
#   --java-only | --dotnet-only   build one front
# Environment: JAVA_HOME, MVN_ARGS (extra Maven arguments), DOTNET_ROOT.
set -u
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

what="${1:-all}"
LOG_DIR="$ENGINE_DIR/target/build-logs"
PUBLISH_DIR="$ENGINE_DIR/target/dotnet-analyzer-publish"

build_java() {
  local mvn log
  mvn="$(mvn_cmd)"
  [ -n "$mvn" ] || { status build engine-java FAIL "mvn not found (and no engine/mvnw)"; return 1; }
  mkdir -p "$LOG_DIR"
  log="$LOG_DIR/engine-java.log"
  # shellcheck disable=SC2086
  if (cd "$ENGINE_DIR" && "$mvn" -B ${MVN_ARGS:-} -DskipTests package) > "$log" 2>&1; then
    status build engine-java OK "engine/target/$ENGINE_JAR_NAME"
  else
    tail -n 40 "$log" >&2
    status build engine-java FAIL "see ${log#"$PRODUCT_ROOT"/}"
    return 1
  fi
}

# Writes an executable launcher <dest> running the sibling dotnet-analyzer-publish/dotnet-analyzer with
# DOTNET_ROOT (needed by Homebrew .NET installs).
write_launcher() { # dest
  {
    echo '#!/usr/bin/env bash'
    echo '# Generated by scripts/engine-build.sh: launches the framework-dependent dotnet-analyzer.'
    [ -n "${DOTNET_ROOT:-}" ] && echo "export DOTNET_ROOT=\"\${DOTNET_ROOT:-$DOTNET_ROOT}\""
    echo 'exec "$(cd "$(dirname "$0")" && pwd)/dotnet-analyzer-publish/dotnet-analyzer" "$@"'
  } > "$1"
  chmod +x "$1"
}

build_dotnet() {
  local log="$LOG_DIR/engine-dotnet.log"
  export_dotnet_root
  mkdir -p "$LOG_DIR"
  rm -rf "$PUBLISH_DIR"
  if dotnet publish "$ENGINE_DIR/src/main/dotnet/DotNetAnalyzer/DotNetAnalyzer.csproj" -c Release \
       --self-contained false -o "$PUBLISH_DIR" > "$log" 2>&1; then
    if [ -x "$PUBLISH_DIR/dotnet-analyzer" ]; then
      rm -f "$ENGINE_DIR/target/dotnet-analyzer"
      write_launcher "$ENGINE_DIR/target/dotnet-analyzer"
    fi
    status build engine-dotnet OK "engine/target/dotnet-analyzer"
  else
    tail -n 40 "$log" >&2
    status build engine-dotnet FAIL "see ${log#"$PRODUCT_ROOT"/}"
    return 1
  fi
}

case "$what" in
  --java-only) build_java ;;
  --dotnet-only) build_dotnet ;;
  all) build_java && build_dotnet ;;
  *) echo "usage: $0 [--java-only|--dotnet-only]" >&2; exit 64 ;;
esac
